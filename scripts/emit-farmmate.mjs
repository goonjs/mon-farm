/**
 * Emits `design/icons/farmmate-masters.ts` from the traced FarmMate originals
 * in `design/icons/farmmate/*.svg` (the "ตัวสวย" set, owner 2026-11-03: the
 * whole app uses them; see docs/stories/e03-s11-farmmate-masters.md).
 *
 *   node scripts/emit-farmmate.mjs           # write
 *   node scripts/emit-farmmate.mjs --check   # exit 1 if the file on disk is stale
 *
 * Each SVG is minified (no xml declaration, title, ids or fixed pixel size;
 * path data rounded to whole units, the viewBox to one decimal) and stored as
 * a string the app parses once and draws with react-native-svg. Every path is
 * absolute (M L C Z), so rounding does not add up along a path: an edge moves
 * at most half a unit of a ~1100-unit viewBox, 0.02 px at 48 px (PR 5, owner
 * 2026-11-03: ~60 KB gzip less than one decimal).
 *
 * The module lives in design/, not src/: its colours are the originals' own
 * fills, and design/ is where raw colour is allowed (scripts/no-raw-colour.test.ts
 * scans src/ only), the same as design/tokens.ts.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const MASTERS_DIR = join(ROOT, 'design/icons/farmmate');
export const OUT = join(ROOT, 'design/icons/farmmate-masters.ts');

/** One number to `decimals` places, keeping a minus even when it rounds to zero (in compact path data it separates two numbers). */
const round = (n, decimals) => {
  const k = 10 ** decimals;
  const r = Math.round(Number(n) * k) / k;
  return r === 0 && n.startsWith('-') ? '-0' : String(Object.is(r, -0) ? 0 : r);
};

/** Only path data and the viewBox are coordinates; every other number stays as written. */
const roundNumbers = (value, decimals) =>
  value.replace(/-?\d*\.\d+/g, (n, at, all) => {
    const r = round(n, decimals);
    // In "1.5.96" the dot of ".96" is its only separator; once rounded ("1"), a space has to take its place.
    return /[\d.]/.test(all[at - 1] ?? '') && /^\d/.test(r) ? ` ${r}` : r;
  });

const ALLOWED = new Set(['svg', 'g', 'path']);

/** One original → the string the app ships. Throws on anything it cannot keep exact. */
export function minifySvg(svg) {
  const body = svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '');
  for (const [, tag] of body.matchAll(/<([a-zA-Z][\w:-]*)/g)) {
    if (!ALLOWED.has(tag)) throw new Error(`unexpected <${tag}>: the minifier only knows svg, g and path`);
  }
  if (/[\d.][eE][-+]?\d/.test(body.match(/\s(?:d|viewBox)="[^"]*"/g)?.join(' ') ?? '')) {
    throw new Error('exponent in path data or viewBox: not supported');
  }
  return body
    .replace(/<svg\b[^>]*>/, (tag) => tag.replace(/\s(?:width|height)="[^"]*"/g, ''))
    .replace(/\sid="[^"]*"/g, '')
    .replace(/\s(d|viewBox)="([^"]*)"/g, (_, name, value) => ` ${name}="${roundNumbers(value, name === 'd' ? 0 : 1)}"`)
    .replace(/>\s+</g, '><')
    .trim();
}

/** The whole generated module, ids in name order. */
export function emitModule() {
  const ids = readdirSync(MASTERS_DIR)
    .filter((f) => f.endsWith('.svg'))
    .map((f) => f.slice(0, -4))
    .sort();
  const rows = ids.map((id) => {
    const svg = minifySvg(readFileSync(join(MASTERS_DIR, `${id}.svg`), 'utf8'));
    if (/['\\\n]/.test(svg)) throw new Error(`${id}: unexpected quote, backslash or newline`);
    return `  '${id}': '${svg}',`;
  });
  const manifest = JSON.parse(readFileSync(join(MASTERS_DIR, 'manifest.json'), 'utf8'));
  const labels = manifest
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .map((m) => {
      if (/['\\\n]/.test(m.labelTh)) throw new Error(`${m.id}: quote, backslash or newline in label`);
      return `  '${m.id}': '${m.labelTh}',`;
    });
  return [
    '// GENERATED by scripts/emit-farmmate.mjs from design/icons/farmmate/*.svg — do not edit.',
    '// Run `npm run icons` after changing an original.',
    '',
    '/** The traced FarmMate originals, minified, by icon id (e.g. `sale.weigh`). */',
    'export const FARMMATE_MASTERS = {',
    ...rows,
    '} as const;',
    '',
    '/** An icon id that has an original; a misspelt id does not compile. */',
    'export type FarmMateArtId = keyof typeof FARMMATE_MASTERS;',
    '',
    '/** Thai label of each icon, from design/icons/farmmate/manifest.json. */',
    'export const FARMMATE_MASTER_LABEL_TH: Readonly<Record<FarmMateArtId, string>> = {',
    ...labels,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = emitModule();
  if (process.argv.includes('--check')) {
    let now = '';
    try {
      now = readFileSync(OUT, 'utf8');
    } catch {
      /* missing counts as stale */
    }
    if (now !== next) {
      console.error('design/icons/farmmate-masters.ts is stale: run `npm run icons`');
      process.exit(1);
    }
    console.log('farmmate-masters.ts is up to date');
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT} (${(next.length / 1024).toFixed(0)} KB)`);
  }
}
