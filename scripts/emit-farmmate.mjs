/**
 * Emits `design/icons/farmmate-masters.ts` from the traced FarmMate originals
 * in `design/icons/farmmate/*.svg` (the "ตัวสวย" set, owner 2026-11-03: the
 * whole app uses them; see docs/stories/e03-s11-farmmate-masters.md).
 *
 *   node scripts/emit-farmmate.mjs           # write
 *   node scripts/emit-farmmate.mjs --check   # exit 1 if the file on disk is stale
 *
 * Each SVG is minified (no xml declaration, title, ids or fixed pixel size;
 * coordinates rounded to one decimal — the viewBox is ~1100 units, so the
 * rounding moves an edge by under 0.01 px at the largest size the app draws)
 * and stored as a string the app draws with react-native-svg's SvgXml.
 *
 * The module lives in design/, not src/: its colours are the originals' own
 * fills, and design/ is where raw colour is allowed (scripts/no-raw-colour.test.ts
 * scans src/ only), the same as design/tokens.ts.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const MASTERS_DIR = join(ROOT, 'design/icons/farmmate');
export const OUT = join(ROOT, 'design/icons/farmmate-masters.ts');

const round = (n) => {
  const r = Math.round(Number(n) * 10) / 10;
  return String(Object.is(r, -0) ? 0 : r);
};

/** One original → the string the app ships. */
export function minifySvg(svg) {
  return svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '')
    .replace(/\s(?:id|width|height)="[^"]*"/g, '')
    .replace(/-?\d+\.\d+/g, round)
    .replace(/>\s+</g, '><')
    .trim();
}

/** The whole generated module, ids in name order. */
export function emitModule() {
  const ids = readdirSync(MASTERS_DIR)
    .filter((f) => f.endsWith('.svg'))
    .map((f) => f.slice(0, -4))
    .sort();
  const rows = ids.map((id) => {
    const svg = minifySvg(readFileSync(join(MASTERS_DIR, `${id}.svg`), 'utf8'));
    if (svg.includes("'") || svg.includes('\\')) throw new Error(`${id}: unexpected quote or backslash`);
    return `  '${id}': '${svg}',`;
  });
  const manifest = JSON.parse(readFileSync(join(MASTERS_DIR, 'manifest.json'), 'utf8'));
  const labels = manifest
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .map((m) => {
      if (m.labelTh.includes("'")) throw new Error(`${m.id}: quote in label`);
      return `  '${m.id}': '${m.labelTh}',`;
    });
  return [
    '// GENERATED by scripts/emit-farmmate.mjs from design/icons/farmmate/*.svg — do not edit.',
    '// Run `npm run icons` after changing an original.',
    '',
    '/** The traced FarmMate originals, minified, by icon id (e.g. `sale.weigh`). */',
    'export const FARMMATE_MASTERS: Readonly<Record<string, string>> = {',
    ...rows,
    '};',
    '',
    '/** Thai label of each icon, from design/icons/farmmate/manifest.json. */',
    'export const FARMMATE_MASTER_LABEL_TH: Readonly<Record<string, string>> = {',
    ...labels,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = emitModule();
  if (process.argv.includes('--check')) {
    let now = '';
    try {
      now = readFileSync(OUT, 'utf8');
    } catch {
      /* missing counts as stale */
    }
    if (now !== next) {
      console.error('design/icons/farmmate-masters.ts is stale: run `npm run icons`');
      process.exit(1);
    }
    console.log('farmmate-masters.ts is up to date');
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT} (${(next.length / 1024).toFixed(0)} KB)`);
  }
}
