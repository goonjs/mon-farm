import { describe, expect, it } from 'vitest';

import { bahtWords } from './baht-words';

describe('bahtWords', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [100, 'หนึ่งบาทถ้วน'],
    [115000, 'หนึ่งพันหนึ่งร้อยห้าสิบบาทถ้วน'],
    [115050, 'หนึ่งพันหนึ่งร้อยห้าสิบบาทห้าสิบสตางค์'],
    [5, 'ศูนย์บาทห้าสตางค์'],
    [1, 'ศูนย์บาทหนึ่งสตางค์'],
    [1100, 'สิบเอ็ดบาทถ้วน'],
    [2100, 'ยี่สิบเอ็ดบาทถ้วน'],
    [10100, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [2000, 'ยี่สิบบาทถ้วน'],
    [1000, 'สิบบาทถ้วน'],
    [2121, 'ยี่สิบเอ็ดบาทยี่สิบเอ็ดสตางค์'],
    [125000000, 'หนึ่งล้านสองแสนห้าหมื่นบาทถ้วน'],
    [12345678900, 'หนึ่งร้อยยี่สิบสามล้านสี่แสนห้าหมื่นหกพันเจ็ดร้อยแปดสิบเก้าบาทถ้วน'],
    [100000000, 'หนึ่งล้านบาทถ้วน'],
    [100000100, 'หนึ่งล้านเอ็ดบาทถ้วน'],
    [100000000000000, 'หนึ่งล้านล้านบาทถ้วน'],
  ])('%i satang → %s', (satang, words) => {
    expect(bahtWords(satang)).toBe(words);
  });

  it('throws RangeError for negative or non-integer satang', () => {
    expect(() => bahtWords(-1)).toThrow(RangeError);
    expect(() => bahtWords(1.5)).toThrow(RangeError);
    expect(() => bahtWords(NaN)).toThrow(RangeError);
  });
});
